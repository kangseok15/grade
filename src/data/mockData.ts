export function itemTypeDetail(
  student: Student | undefined,
  exam: ExamRecord | undefined,
  subjectKey: SubjectKey,
  itemNum: number
): ItemBlueprintItem | null {
  if (!exam || !exam.examDate) return null;
  const grade = student?.grade || (exam.label.includes('고3') ? '3' : exam.label.includes('고2') ? '2' : '1');
  const year = exam.examDate.slice(0, 4);
  const month = exam.examDate.slice(5, 7);
  const key = `${grade}-${year}-${month}`;
  const map =
    ITEM_TYPE_MAPS[key] ||
    ITEM_TYPE_MAPS[`${grade}-2026-${month}`] ||
    ITEM_TYPE_MAPS[`${grade}-2026-03`];
  const ranges = map?.[subjectKey];
  if (!ranges) return null;
  for (let i = 0; i < ranges.length; i++) {
    const r = ranges[i];
    if (r.items && r.items.includes(itemNum)) {
      return r;
    }
    if (r.from != null && r.to != null && itemNum >= r.from && itemNum <= r.to) {
      return r;
    }
  }
  return null;
}

