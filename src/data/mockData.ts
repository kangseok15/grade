export function subjectDisplayName(s: SubjectConfig, examSubjData?: { name?: string }, grade?: string): string {
  // 탐구 과목에 구체적인 명칭(예: 통합사회, 통합과학, 사회문화 등)이 지정되어 있으면 과목명만 명확히 반환
  if ((s.key === 'elective1' || s.key === 'elective2') && examSubjData?.name) {
    return examSubjData.name;
  }
  // 1, 2학년은 국어/수학이 전원 공통이므로 불필요한 선택과목명 부착 제외
  if (grade === '1' || grade === '2') {
    return s.name;
  }
  // 3학년에서 국어/수학 선택과목(화법과 작문, 미적분 등)이 있을 때만 표기
  if (examSubjData?.name && (s.key === 'korean' || s.key === 'math')) {
    return `${s.name}(${examSubjData.name})`;
  }
  return s.name;
}

